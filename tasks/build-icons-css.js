/**
 * Writes assets/flowable-bpmn-js.css from the typed task icons in
 * lib/features/typed-tasks/icons.js: one `flowable-icon-<type>` class per
 * icon for the palette and the replace menu. The icons are CSS masks filled
 * with the text color, so they follow the theme like the bpmn-js icons.
 *
 *   node tasks/build-icons-css.js           writes the file
 *   node tasks/build-icons-css.js --check   fails when the file is outdated
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { ICONS, toSvg } from '../lib/features/typed-tasks/icons.js';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const FILE = path.join(ROOT, 'assets', 'flowable-bpmn-js.css');

export function buildCss() {
  const rules = Object.keys(ICONS).map(type => {
    const url = `url("data:image/svg+xml,${ encodeURIComponent(toSvg(type, '#000')) }")`;

    return `.flowable-icon-${ type }::before {\n  -webkit-mask-image: ${ url };\n  mask-image: ${ url };\n}`;
  });

  return `/*
 * @jylups/flowable-bpmn-js: icons of the typed service tasks in the palette
 * and the replace menu. Generated by tasks/build-icons-css.js; do not edit.
 */

.flowable-icon::before {
  content: '';
  display: inline-block;
  width: 1em;
  height: 1em;
  vertical-align: middle;
  background-color: currentColor;
  -webkit-mask-repeat: no-repeat;
  mask-repeat: no-repeat;
  -webkit-mask-position: center;
  mask-position: center;
  -webkit-mask-size: contain;
  mask-size: contain;
}

${ rules.join('\n\n') }
`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const css = buildCss();

  if (process.argv.includes('--check')) {
    if (!fs.existsSync(FILE) || fs.readFileSync(FILE, 'utf8') !== css) {
      console.error('assets/flowable-bpmn-js.css is outdated; run npm run icons');
      process.exit(1);
    }
  } else {
    fs.mkdirSync(path.dirname(FILE), { recursive: true });
    fs.writeFileSync(FILE, css);
    console.log(`wrote ${ path.relative(ROOT, FILE) }`);
  }
}
